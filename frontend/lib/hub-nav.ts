/** Compile-time proof that registry route names exist in the generated map. */
export type HubNavRouteName = keyof typeof routes;

export interface HubNavRoute {
  /** Stable Django route identifier. */
  name: HubNavRouteName;
  /** Generated by `routes`; registry consumers never concatenate paths. */
  href: string;
}

export interface HubNavActiveMatch {
  /** Paths that activate the item, including their detail descendants. */
  prefixes: string[];
  /** More-specific sibling paths that belong to another item. */
  exclusions?: string[];
}

export interface HubNavItem {
  /** Stable registry identity; never derived from copy. */
  key: string;
  label: string;
  route: HubNavRoute;
  icon: LucideIcon;
  group: HubNavGroupKey;
  order: number;
  access: "authenticated" | "permission-protected";
  /** Effective permission requirements. Both `any` and `all` are supported. */
  permissions: PermissionCheck;
  /**
   * Role codes this destination is *relevant* to. Absent means everyone.
   *
   * This is presentation, not authorization, and the two must not be confused:
   *
   * - It can only ever **hide** an entry. It never reveals one, and a hidden
   *   route is exactly as reachable as it was before.
   * - It is legal only on items that require no permissions. Where a
   *   permission exists it already expresses relevance, and adding a role
   *   filter on top would hide a destination somebody was deliberately
   *   granted. `validateHubNavRegistry` enforces this.
   * - A superuser is never filtered by it.
   *
   * Authorization stays where it belongs: `permissions` here, and
   * `enforce_policy` on the view.
   */
  roles?: readonly string[];
  /**
   * Copy-only relabeling for the roles the destination reads differently to.
   * Like `roles`, this is presentation: it changes wording, never visibility,
   * reachability, or authorization. Matching is on stable role codes, and a
   * superuser is not special-cased — the label follows the roles a person
   * actually holds.
   */
  labelForRoles?: { roles: readonly string[]; label: string };
  /** Missing keys hide; explicit false keys render a protected Soon route. */
  feature?: string;
  requiresOffice?: boolean;
  activeMatch: HubNavActiveMatch;
  /** Optional nested/collapsible administrative structure. */
  section?: HubNavSectionKey;
}

export interface HubNavGroupDefinition {
  key: HubNavGroupKey;
  label: string;
  order: number;
}

export interface HubNavSectionDefinition {
  key: HubNavSectionKey;
  label: string;
  group: HubNavGroupKey;
  order: number;
  defaultExpanded: boolean;
}

export interface ResolvedHubNavGroup extends HubNavGroupDefinition {
  items: ResolvedHubNavItem[];
}

export interface ResolvedHubNavSection extends HubNavSectionDefinition {
  items: ResolvedHubNavItem[];
}

export interface ResolvedHubNavItem extends HubNavItem {
  availability: "available" | "coming-soon";
}

function route(name: HubNavRouteName, href: string): HubNavRoute {
  return { name, href };
}

function active(...prefixes: string[]): HubNavActiveMatch {
  return { prefixes };
}

