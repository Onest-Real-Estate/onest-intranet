function normalizedPath(value: string): string {
  const path = value.split(/[?#]/)[0] || "/";
  return path.length > 1 ? path.replace(/\/+$/, "") : path;
}

function pathMatches(current: string, prefix: string): boolean {
  const path = normalizedPath(current);
  const candidate = normalizedPath(prefix);
  return path === candidate || path.startsWith(`${candidate}/`);
}

export function isHubNavItemActive(item: HubNavItem, current: string): boolean {
  if (item.activeMatch.exclusions?.some((path) => pathMatches(current, path))) {
    return false;
  }
  return item.activeMatch.prefixes.some((path) => pathMatches(current, path));
}

export function hubNavItemDescription(item: ResolvedHubNavItem): string | null {
  return item.availability === "coming-soon" ? `${item.label} is coming soon` : null;
}

function hasDeclaredPermissions(item: HubNavItem): boolean {
  return Boolean(item.permissions.all?.length || item.permissions.any?.length);
}

/**
 * Whether a destination is worth showing this reader.
 *
 * Only ever narrows, and only for items that ask for no permission — see
 * `HubNavItem.roles`. A superuser is exempt so a platform administrator can
 * still reach every destination from the rail.
 */
function isRelevantToRoles(user: User, item: HubNavItem): boolean {
  if (!item.roles || user.isSuperuser) {
    return true;
  }
  if (!Array.isArray(user.roles)) {
    return false;
  }
  return item.roles.some((code) => user.roles.includes(code));
}

/** Registry copy, swapped for the roles that read the destination differently. */
function labelFor(user: User, item: HubNavItem): string {
  const override = item.labelForRoles;
  if (!override || !Array.isArray(user.roles)) {
    return item.label;
  }
  return override.roles.some((code) => user.roles.includes(code))
    ? override.label
    : item.label;
}

/** Return human-readable contract violations without mutating the registry. */
export function validateHubNavRegistry(
  registry: HubNavItem[] = HUB_NAV_REGISTRY,
  groups: HubNavGroupDefinition[] = HUB_NAV_GROUPS,
  sections: HubNavSectionDefinition[] = HUB_NAV_SECTIONS,
): string[] {
  const errors: string[] = [];
  const groupKeys = new Set<HubNavGroupKey>();
  const groupOrders = new Set<number>();
  for (const group of groups) {
    if (groupKeys.has(group.key)) {
      errors.push(`duplicate group key: ${group.key}`);
    }
    if (groupOrders.has(group.order)) {
      errors.push(`duplicate group order: ${group.order}`);
    }
    groupKeys.add(group.key);
    groupOrders.add(group.order);
  }

  const sectionKeys = new Set<HubNavSectionKey>();
  const sectionOrders = new Set<string>();
  for (const section of sections) {
    if (sectionKeys.has(section.key)) {
      errors.push(`duplicate section key: ${section.key}`);
    }
    if (!groupKeys.has(section.group)) {
      errors.push(`unknown section group for ${section.key}: ${section.group}`);
    }
    const scopedOrder = `${section.group}:${section.order}`;
    if (sectionOrders.has(scopedOrder)) {
      errors.push(`duplicate section order: ${scopedOrder}`);
    }
    sectionKeys.add(section.key);
    sectionOrders.add(scopedOrder);
  }

  const sectionByKey = new Map(sections.map((section) => [section.key, section]));
  const seenKeys = new Set<string>();
  const seenDestinations = new Set<string>();
  const seenOrders = new Set<string>();

  for (const item of registry) {
    if (seenKeys.has(item.key)) {
      errors.push(`duplicate item key: ${item.key}`);
    }
    seenKeys.add(item.key);

    const destination = normalizedPath(item.route.href);
    if (seenDestinations.has(destination)) {
      errors.push(`duplicate destination: ${destination}`);
    }
    seenDestinations.add(destination);

    if (!groupKeys.has(item.group)) {
      errors.push(`unknown group for ${item.key}: ${item.group}`);
    }
    if (!item.route.href.startsWith("/")) {
      errors.push(`invalid route for ${item.key}: ${item.route.href}`);
    }
    if (item.order < 0 || !Number.isInteger(item.order)) {
      errors.push(`invalid order for ${item.key}: ${item.order}`);
    }
    const orderScope = `${item.group}:${item.section ?? "root"}:${item.order}`;
    if (seenOrders.has(orderScope)) {
      errors.push(`duplicate order: ${orderScope}`);
    }
    seenOrders.add(orderScope);

    if (item.access === "permission-protected" && !hasDeclaredPermissions(item)) {
      errors.push(`protected item lacks permissions: ${item.key}`);
    }
    if (item.roles) {
      if (item.roles.length === 0) {
        // An empty list would hide the entry from everyone, which is a
        // deletion written as a filter.
        errors.push(`item declares an empty role list: ${item.key}`);
      }
      if (hasDeclaredPermissions(item)) {
        // Relevance may not double as authorization. See `HubNavItem.roles`.
        errors.push(`permission-protected item declares roles: ${item.key}`);
      }
      for (const code of item.roles) {
        if (!getRoleCatalogEntry(code)) {
          errors.push(`unknown role for ${item.key}: ${code}`);
        }
      }
    }
    if (item.labelForRoles) {
      if (item.labelForRoles.roles.length === 0) {
        errors.push(`item declares an empty label role list: ${item.key}`);
      }
      if (!item.labelForRoles.label.trim()) {
        errors.push(`item declares an empty role label: ${item.key}`);
      }
      for (const code of item.labelForRoles.roles) {
        if (!getRoleCatalogEntry(code)) {
          errors.push(`unknown label role for ${item.key}: ${code}`);
        }
      }
    }
    if (item.activeMatch.prefixes.length === 0) {
      errors.push(`item lacks active match prefixes: ${item.key}`);
    }
    if (item.section) {
      const section = sectionByKey.get(item.section);
      if (!section || section.group !== item.group) {
        errors.push(`invalid section for ${item.key}: ${item.section}`);
      }
    }
  }
  return errors;
}

/**
 * Permission and availability resolver used by every visual navigation mode.
 * Unknown permissions, missing feature keys, and required context fail closed.
 * Explicit false features remain protected Soon entries. Dedupe is by both
 * registry key and destination so aliases cannot leak in.
 */
export function resolveHubNav(
  user: User | null,
  features: HubFeatures = {},
  primaryOffice: PrimaryOffice | null = null,
  registry: HubNavItem[] = HUB_NAV_REGISTRY,
  groups: HubNavGroupDefinition[] = HUB_NAV_GROUPS,
): ResolvedHubNavGroup[] {
  if (!user || !Array.isArray(user.permissions)) {
    return [];
  }

  const seenKeys = new Set<string>();
  const seenDestinations = new Set<string>();
  const visible: ResolvedHubNavItem[] = registry
    .filter((item) => {
      const destination = normalizedPath(item.route.href);
      if (seenKeys.has(item.key) || seenDestinations.has(destination)) {
        return false;
      }
      if (!hasPermission(user, item.permissions)) {
        return false;
      }
      if (!isRelevantToRoles(user, item)) {
        return false;
      }
      if (item.feature !== undefined && features[item.feature] === undefined) {
        return false;
      }
      if (item.requiresOffice && primaryOffice === null) {
        return false;
      }
      seenKeys.add(item.key);
      seenDestinations.add(destination);
      return true;
    })
    .map((item) => ({
      ...item,
      label: labelFor(user, item),
      availability:
        item.feature !== undefined && features[item.feature] === false
          ? ("coming-soon" as const)
          : ("available" as const),
    }))
    .sort(
      (left, right) => left.order - right.order || left.key.localeCompare(right.key),
    );

  return [...groups]
    .sort((left, right) => left.order - right.order)
    .map((group) => ({
      ...group,
      items: visible
        .filter((item) => item.group === group.key)
        .sort(
          (left, right) =>
            sectionOrder(left.section) - sectionOrder(right.section) ||
            left.order - right.order ||
            left.key.localeCompare(right.key),
        ),
    }))
    .filter((group) => group.items.length > 0);
}

/**
 * Split a resolved rail into the destinations that work and the ones that do
 * not yet.
 *
 * Registered-but-unbuilt modules stay visible to authorized readers — that is
 * a deliberate product decision, so people can see what is coming. Scattering
 * them through the groups was the problem: an agent's rail was fourteen
 * entries of which eight went nowhere, and two whole headings ("Tools",
 * "Directory") contained nothing else. A reader learning the product cannot
 * tell the shape of what they have from a list that is mostly promises.
 *
 * Gathering them into one disclosure keeps the promise and gives the rail back
 * its meaning: every heading now names live work, and what is coming is one
 * countable row somebody can open on purpose.
 *
 * A group left with no live items disappears. Permission filtering is
 * untouched — a pending item a reader may not hold never reaches either half.
 */
export function partitionByAvailability(groups: ResolvedHubNavGroup[]): {
  live: ResolvedHubNavGroup[];
  pending: ResolvedHubNavItem[];
} {
  const pending: ResolvedHubNavItem[] = [];
  const live: ResolvedHubNavGroup[] = [];

  for (const group of groups) {
    const available = group.items.filter((item) => {
      if (item.availability === "coming-soon") {
        pending.push(item);
        return false;
      }
      return true;
    });
    if (available.length > 0) {
      live.push({ ...group, items: available });
    }
  }
  return { live, pending };
}

function sectionOrder(key: HubNavSectionKey | undefined): number {
  if (!key) {
    return -1;
  }
  return HUB_NAV_SECTIONS.find((section) => section.key === key)?.order ?? 0;
}

export function resolveHubNavSections(
  group: ResolvedHubNavGroup,
  sections: HubNavSectionDefinition[] = HUB_NAV_SECTIONS,
): ResolvedHubNavSection[] {
  return sections
    .filter((section) => section.group === group.key)
    .sort((left, right) => left.order - right.order)
    .map((section) => ({
      ...section,
      items: group.items.filter((item) => item.section === section.key),
    }))
    .filter((section) => section.items.length > 0);
}

/**
 * Read only known section keys from storage. Corrupt/missing state falls back
 * to reviewed defaults; stale keys from older deployments are ignored.
 */
export function parseHubNavExpansion(
  stored: string | null,
  allowedSections: HubNavSectionDefinition[] = HUB_NAV_SECTIONS,
): Set<HubNavSectionKey> {
  const allowed = new Set(allowedSections.map((section) => section.key));
  const defaults = new Set(
    allowedSections
      .filter((section) => section.defaultExpanded)
      .map((section) => section.key),
  );
  if (stored === null) {
    return defaults;
  }
  try {
    const value: unknown = JSON.parse(stored);
    if (!Array.isArray(value) || !value.every((item) => typeof item === "string")) {
      return defaults;
    }
    return new Set(
      value.filter((item): item is HubNavSectionKey =>
        allowed.has(item as HubNavSectionKey),
      ),
    );
  } catch {
    return defaults;
  }
}
